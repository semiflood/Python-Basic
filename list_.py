# 리스트 함수

# 리스트명. insert(인덱스 번호, 추가할 값)
# insert()함수는 인덱스 번호 위에 추가, 기존 위치에 있는 값은 뒤로 밀림
# 인덱스 번호가 리스트의 버위를 벗어나는 경우 값을 리스트 제일 뒤에 추가됨

# 리스트명.append(추가할 값)
# append() 함수는 리스트 제일 뒤에 값을 추가

# del(리스트명[인덱스 번호])
# del()함수는 인덱스 번호에 해당하는 값을 리스트에서 삭제
# 만약 삭제한 위치 뒤에 값이 잇으면 앞으로 당겨짐
# 인덱스 번호가 범위를 벗에나면 에러 발생

# 리스트명.remove(삭제할 값)
# remove() 함수는 리스트에서 특정 값을 삭제
# 만약 삭제할 값이 여러게면 제일 앞에 있는 한개의 값만 삭제
# 만약 삭제할 값이 리스트에 없으면 에러 발생

# 리스트명.index(인덱스 번호를 찾을 값)
# index()함수는 리스트의 크기(길이)를 알려줌
# 특정 값이 여러게면 가장 앞에 있는 인덱스 번호를 알려줌
# 값이 리스트에 없을 경우 에러 발생

# len(리스트명)
# len()함수는 리스트의 크기(길이)를 알려줌

# sum(리스트명)
# sum()함수는 리스트의 값을 전부 더해줌, 리스트 내부에 값이 전부 숫자일 경우만 가능

# 리스트명.count(개수를 알고 싶은 값)
# count()함수는 특정 값이 리스트에 멏게 있는지 알려줌
# 만약 특정 값이 리스트에 없으면 0

# 리스트명.sort()
# sort()함수는 리스트의 내용을 오름차순으로 정렬

# insert()와 같이 리스트 변수와 .을 같이 사용하는 함수는 리스트에만 사용가능하고
